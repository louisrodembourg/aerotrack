"""Markdown rendering of evaluation reports, and README table generation.

The README results table is rewritten between two markers from reports/*/results.json,
which are themselves written only by tracked runs: no number reaches the README by hand.
"""

from __future__ import annotations

import json
from pathlib import Path

from aerotrack.paths import REPORTS_DIR

START, END = "<!-- results:start -->", "<!-- results:end -->"


def _pct(v) -> str:
    return "n/a" if v is None or v != v else f"{100 * v:.1f}"


def _ms(v) -> str:
    return f"{v:.1f}"


def _versions(lat: dict) -> str:
    env, rt = lat["env"], lat["runtime"]
    parts = [f"torch {env['torch']}"] if rt["backend"] == "torch" else [f"ORT {env['onnxruntime']}"]
    if env.get("tensorrt"):
        parts.append(f"TRT {env['tensorrt']}")
    if env.get("jetson_power_mode"):
        parts.append(f"power {env['jetson_power_mode']}")
    return ", ".join(parts)


def _input(a: dict) -> str:
    """Input size, plus the tile grid for tiled inference: `640 (2x2+full)`."""
    rt = a.get("runtime") or {}
    if not rt.get("tiles"):
        return str(a["imgsz"])
    rows, cols = rt["tiles"]
    return f"{a['imgsz']} ({rows}x{cols}{'+full' if rt.get('tile_full') else ''})"


def accuracy_table(results: list[dict]) -> str:
    rows = ["| Model | Class map | imgsz | mAP50-95 | mAP50 | AP_small | AP_medium | AP_large | Images | Run |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for r in results:
        a = r["accuracy"]
        rows.append(f"| {r['model']} | {a['class_map']} | {_input(a)} | {_pct(a['mAP50-95'])} | "
                    f"{_pct(a['mAP50'])} | {_pct(a['AP_small'])} | {_pct(a['AP_medium'])} | "
                    f"{_pct(a['AP_large'])} | {a['n_images']} | `{r['run_id']}` |")
    return "\n".join(rows)


def _device(env: dict) -> str:
    """Device name plus the power state when it is known: on a Mac, battery or Low Power
    Mode; on a Jetson, the nvpmodel mode. Older records without it print the name only."""
    name = env["device_name"]
    if mac := env.get("macos_power"):
        state = "AC" if mac.get("source") == "ac" else "battery"
        if mac.get("low_power_mode"):
            state += ", Low Power Mode"
        name += f" [{state}]"
    if jetson := env.get("jetson_power_mode"):
        name += f" [{jetson.splitlines()[0]}]"
    return name


def latency_table(results: list[dict], budget: float) -> str:
    rows = ["| Model | Backend | Device | Versions | Pre | Infer | Post | Total median | Total p95 | FPS (median) | ≥ budget |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in results:
        for lat in r["latency"]:
            rows.append(
                f"| {r['model']} | {lat['runtime']['backend']} | {_device(lat['env'])} | "
                f"{_versions(lat)} | {_ms(lat['preprocess']['median_ms'])} | "
                f"{_ms(lat['inference']['median_ms'])} | {_ms(lat['postprocess']['median_ms'])} | "
                f"{_ms(lat['total']['median_ms'])} | {_ms(lat['total']['p95_ms'])} | "
                f"{lat['fps_median']:.1f} | {'yes' if lat['fps_median'] >= budget else 'no'} |")
    return "\n".join(rows)


def per_class_table(results: list[dict]) -> str:
    classes = list(results[0]["accuracy"]["per_class"])
    rows = ["| Model | " + " | ".join(classes) + " |", "|---|" + "---|" * len(classes)]
    for r in results:
        pc = r["accuracy"]["per_class"]
        rows.append(f"| {r['model']} | " + " | ".join(_pct(pc[c]["AP"]) for c in classes) + " |")
    return "\n".join(rows)


def render_markdown(payload: dict) -> str:
    results, budget = payload["results"], payload["budget_fps"]
    first = results[0]["accuracy"]
    excluded = "\n".join(f"- `{k}`: {v}" for k, v in first["excluded_classes"].items()) or "- none"
    mapping = ", ".join(f"`{k}`→`{v}`" for k, v in first["model_class_to_target"].items())
    return f"""# {payload['name']}

Generated by `aerotrack evaluate`; every row links to a tracked run (`runs/<id>/run.json`).
AP in %, COCO protocol with maxDets={first['max_det']}, ignored regions removed with the
dataset's official rule. Latency in ms, batch 1, images pre-decoded in memory.

## Accuracy

{accuracy_table(results)}

Per-class AP50-95:

{per_class_table(results)}

Class mapping (model → evaluated class): {mapping}

Excluded classes (treated as ignore regions):
{excluded}

## Latency

Budget: {budget} FPS end-to-end. **Tracking is not yet part of the measured pipeline**
(pre + inference + post only), so these FPS are an upper bound on the final pipeline.

{latency_table(results, budget)}
"""


def tracking_table(results: list[dict]) -> str:
    """Headline on the sequences the detector never saw; all sequences alongside."""
    n_unseen = len(results[0]["accuracy"]["sequences"]["unseen"])
    n_all = len(results[0]["accuracy"]["sequences"]["all"])
    rows = [f"| Model | Tracker | imgsz | HOTA | MOTA | IDF1 | IDSW | HOTA, all {n_all} seq. | Run |",
            "|---|---|---|---|---|---|---|---|---|"]
    for r in results:
        a = r["accuracy"]
        rows.append(f"| {r['model']} | {a['tracker']['type']} | {_input(a)} | {_pct(a['HOTA'])} | "
                    f"{_pct(a['MOTA'])} | {_pct(a['IDF1'])} | {a['IDSW']} | "
                    f"{_pct(a['all_sequences']['HOTA'])} | `{r['run_id']}` |")
    return f"HOTA, MOTA, IDF1, IDSW on the {n_unseen} sequences unseen by the detector:\n\n" + \
        "\n".join(rows)


def tracking_per_class_table(results: list[dict]) -> str:
    classes = results[0]["accuracy"]["classes"]
    rows = ["| Model | " + " | ".join(f"{c} HOTA / IDF1" for c in classes) + " |",
            "|---|" + "---|" * len(classes)]
    for r in results:
        pc = r["accuracy"]["per_class"]
        rows.append(f"| {r['model']} | " + " | ".join(
            f"{_pct(pc[c]['HOTA'])} / {_pct(pc[c]['IDF1'])}" for c in classes) + " |")
    return "\n".join(rows)


def tracking_latency_table(results: list[dict], budget: float) -> str:
    """End-to-end frame time, tracker included. FPS is taken on the median frame time for
    a single detector, on the mean for a keyframe pipeline whose frames cost unevenly
    (`budget_basis`); mean, p95 and max are shown for every row."""
    rows = ["| Model | Backend | Device | Versions | Track | Total median | Total mean | Total p95 | Total max | FPS | ≥ budget |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in results:
        for lat in r["latency"]:
            basis = lat.get("budget_basis", "median")
            fps = lat.get(f"fps_{basis}", 1000.0 / lat["total"][f"{basis}_ms"])
            rows.append(
                f"| {r['model']} | {lat['runtime']['backend']} | {_device(lat['env'])} | "
                f"{_versions(lat)} | {_ms(lat['tracking']['median_ms'])} | "
                f"{_ms(lat['total']['median_ms'])} | {_ms(lat['total']['mean_ms'])} | "
                f"{_ms(lat['total']['p95_ms'])} | {_ms(lat['total']['max_ms'])} | "
                f"{fps:.1f} ({basis}) | {'yes' if fps >= budget else 'no'} |")
    return "\n".join(rows)


def render_tracking_markdown(payload: dict) -> str:
    results, budget = payload["results"], payload["budget_fps"]
    first = results[0]["accuracy"]
    trk = ", ".join(f"{k}={v}" for k, v in first["tracker"].items())
    lat = (results[0]["latency"] or [{}])[0]
    return f"""# {payload['name']}

Generated by `aerotrack evaluate`; every row links to a tracked run (`runs/<id>/run.json`).
Multi-object tracking on `{first['split']}`, scored with TrackEval per class
({', '.join(first['classes'])}); HOTA, MOTA, IDF1 in % are the means over classes, IDSW
the sum. Headline scores use only the sequences whose source video has no frame in
VisDrone-DET train or val ({len(first['sequences']['unseen'])} of
{len(first['sequences']['all'])}; excluded: {', '.join(sorted(set(first['sequences']['all']) - set(first['sequences']['unseen']))) or 'none'}). Tracker outputs and ground truth both have ignored regions removed with the
dataset's official rule. Detector threshold {first['conf']}; tracker: {trk}.

## Tracking accuracy

{tracking_table(results)}

Per class (unseen sequences):

{tracking_per_class_table(results)}

## End-to-end latency

Budget: {budget} FPS, **tracking included**: detector stages plus the tracker update, per
frame, over {lat.get('n_distinct_frames', 'n/a')} consecutive frames of
`{lat.get('sequence', 'n/a')}` (decoded beforehand). Latency in ms, batch 1. FPS is on the
median frame time for a single detector, on the mean (throughput) for keyframe pipelines,
whose keyframes cost more than the frames between them (see the max column).

{tracking_latency_table(results, budget)}
"""


def readme_section(reports_dir: Path = REPORTS_DIR) -> str:
    blocks = []
    for path in sorted(reports_dir.glob("*/results.json")):
        payload = json.loads(path.read_text())
        rel = path.parent.relative_to(reports_dir.parent)
        if payload.get("kind") == "tuning":
            best = "\n".join(f"- {r['model']}: " + ", ".join(
                f"{k}={v}" for k, v in r["best"]["tracker"].items() if k != "type") +
                f" (HOTA {_pct(r['best']['HOTA'])} on {r['frames']} tuning frames)"
                for r in payload["results"])
            blocks.append(f"#### {payload['name']} ([full report]({rel}/results.md))\n\n"
                          f"Selected tracker thresholds (MOT sequences unseen by the detector, "
                          f"not test-dev):\n\n{best}\n")
            continue
        if payload.get("kind") == "tracking":
            tables = (f"{tracking_table(payload['results'])}\n\n"
                      f"{tracking_latency_table(payload['results'], payload['budget_fps'])}\n")
        else:
            tables = (f"{accuracy_table(payload['results'])}\n\n"
                      f"{latency_table(payload['results'], payload['budget_fps'])}\n")
        blocks.append(f"#### {payload['name']} ([full report]({rel}/results.md))\n\n{tables}")
    return "\n".join(blocks) if blocks else "_No tracked results yet._\n"


def update_readme(readme: Path) -> None:
    text = readme.read_text()
    if START not in text or END not in text:
        raise ValueError(f"{readme} has no {START} ... {END} markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    readme.write_text(f"{head}{START}\n{readme_section()}\n{END}{tail}")
